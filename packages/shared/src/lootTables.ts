/**
 * Per-container loot. Each searchable furniture type lists the items it can
 * roll, with that container's own chance and stack size. A chance of 10 means
 * 10 percent. Rolls are independent, and the same chances apply everywhere.
 */

export type LootRoll = {
  id: string;
  /** 0 to 1. Built from a percent via {@link pct}. */
  chance: number;
  minQty: number;
  maxQty: number;
};

/** `chancePercent` is 10 for 10%, 0.8 for 0.8%, 100 for a sure roll. */
export function pct(
  id: string,
  chancePercent: number,
  minQty = 1,
  maxQty = minQty,
): LootRoll {
  return { id, chance: chancePercent / 100, minQty, maxQty };
}

export function rollLootRolls(
  rolls: readonly LootRoll[],
  rng: () => number,
): { id: string; quantity: number }[] {
  const results: { id: string; quantity: number }[] = [];
  for (const roll of rolls) {
    if (rng() >= roll.chance) continue;
    const span = roll.maxQty - roll.minQty + 1;
    const quantity = roll.minQty + Math.floor(rng() * span);
    if (quantity <= 0) continue;
    results.push({ id: roll.id, quantity });
  }
  return results;
}

